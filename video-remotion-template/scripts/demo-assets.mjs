import fs from 'node:fs';
import path from 'node:path';
import {ROOT,json,writeJson} from './files.mjs';
import {pcmWave} from './pcm.mjs';
// A deterministic technical fixture, not a production score or an AI music service.
const dir=path.join(ROOT,'projects/audio-demo/assets');fs.mkdirSync(dir,{recursive:true});
const rate=44100,duration=12,samples=new Float64Array(rate*duration*2);
for(let i=0;i<rate*duration;i++){
  const t=i/rate,envelope=Math.min(1,t/.4,(duration-t)/.7);
  const value=envelope*(.07*Math.sin(2*Math.PI*130.8128*t)+.035*Math.sin(2*Math.PI*196*t)+.022*Math.sin(2*Math.PI*261.6256*t))*(.85+.15*Math.cos(2*Math.PI*t/3));
  samples[2*i]=value;samples[2*i+1]=value;
}
fs.writeFileSync(path.join(dir,'reference-bed.wav'),pcmWave(samples,rate).buffer);
writeJson(path.join(dir,'index.json'),{schemaVersion:1,items:[{id:'reference-bed',path:'reference-bed.wav',type:'audio',source:'Generated by scripts/demo-assets.mjs; continuous harmonic technical fixture',license:'Project-generated technical sample'}]});
console.log('已生成 12 秒连续测试配乐；需人工试听，不代表正式配乐方案。');
